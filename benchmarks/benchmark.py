"""Spark performance experiments on a scaled-up copy of the silver encounters table.

Writes docs/performance.md. Run after the pipeline: `make bench`.
1. CSV vs parquet: same aggregation, two file formats
2. Partition pruning: filter on year against a partitioned vs an unpartitioned copy
3. Broadcast join vs sort-merge join for fact_encounter x dim_patient
"""
import shutil
import time

from pyspark.sql import functions as F

from clinicalflow.config import GOLD, LAKE, ROOT, SILVER, spark_session

SCALE = 50  # copies of the data, each with fresh ids, so timings are not dominated by Spark start-up
WORK = LAKE / "bench"
OUT = ROOT / "docs" / "performance.md"


def timed(fn, repeats=3):
    best = float("inf")
    for _ in range(repeats):
        start = time.perf_counter()
        fn()
        best = min(best, time.perf_counter() - start)
    return best


def plan(df):
    return df._jdf.queryExecution().executedPlan().toString()


def main():
    spark = spark_session("clinicalflow-bench")
    spark.sparkContext.setLogLevel("ERROR")
    shutil.rmtree(WORK, ignore_errors=True)

    enc = spark.read.parquet(str(SILVER / "encounters"))
    big = (enc.crossJoin(spark.range(SCALE).withColumnRenamed("id", "copy"))
              .withColumn("encounter_id", F.concat_ws("-", "encounter_id", "copy")).drop("copy"))
    big.write.partitionBy("year").parquet(str(WORK / "partitioned"))
    big.write.parquet(str(WORK / "flat"))
    big.write.option("header", True).csv(str(WORK / "csv"))
    n = spark.read.parquet(str(WORK / "flat")).count()
    year = spark.read.parquet(str(WORK / "flat")).groupBy("year").count().orderBy(F.desc("count")).first()["year"]

    agg = lambda df: df.groupBy("encounter_class").agg(F.avg("total_claim_cost")).collect()  # noqa: E731
    csv_s = timed(lambda: agg(spark.read.option("header", True).option("inferSchema", True).csv(str(WORK / "csv"))))
    pq_s = timed(lambda: agg(spark.read.parquet(str(WORK / "flat"))))

    filt = lambda path: spark.read.parquet(str(WORK / path)).filter(F.col("year") == year)  # noqa: E731
    flat_s = timed(lambda: filt("flat").agg(F.sum("total_claim_cost")).collect())
    part_s = timed(lambda: filt("partitioned").agg(F.sum("total_claim_cost")).collect())
    part_plan = [line.strip() for line in plan(filt("partitioned")).splitlines() if "PartitionFilters" in line]

    fact = spark.read.parquet(str(WORK / "partitioned"))
    dim = spark.read.parquet(str(GOLD / "dim_patient"))
    join = lambda f, d: f.join(d, "patient_id").groupBy("age_group").count().collect()  # noqa: E731
    spark.conf.set("spark.sql.autoBroadcastJoinThreshold", -1)
    spark.conf.set("spark.sql.adaptive.enabled", "false")
    smj_s = timed(lambda: join(fact, dim))
    smj_plan = "SortMergeJoin" in plan(fact.join(dim, "patient_id"))
    bc_s = timed(lambda: join(fact, F.broadcast(dim)))
    bc_plan = "BroadcastHashJoin" in plan(fact.join(F.broadcast(dim), "patient_id"))
    spark.stop()

    def speedup(slow, fast):
        return f"{slow / fast:.1f}x faster"

    OUT.write_text(f"""# Performance notes

Generated by `benchmarks/benchmark.py` on a local machine (Spark `local[*]`), using the silver encounters
table copied {SCALE} times: **{n:,} rows**. Each timing is the best of 3 runs, in seconds. Absolute numbers
depend on the laptop; the ratios are the point.

| Experiment | Slower option | Faster option | Result |
|---|---|---|---|
| File format (group-by on cost) | CSV with schema inference: {csv_s:.2f}s | Parquet: {pq_s:.2f}s | {speedup(csv_s, pq_s)} |
| Filter `year = {year}` | Unpartitioned parquet: {flat_s:.2f}s | Partitioned by year: {part_s:.2f}s | {speedup(flat_s, part_s)} |
| Join fact to `dim_patient` | Sort-merge join (shuffle both sides): {smj_s:.2f}s | Broadcast hash join: {bc_s:.2f}s | {speedup(smj_s, bc_s)} |

## Why

- **Parquet vs CSV**: parquet is columnar and typed. Spark reads only the 2 columns the query needs and skips
  parsing text; CSV must be read in full and, with `inferSchema`, read twice.
- **Partition pruning**: with `partitionBy("year")` each year is its own folder. Spark turns the filter into
  a `PartitionFilters` entry in the plan and never opens the other folders:
  `{part_plan[0][:160] if part_plan else 'n/a'}`
- **Broadcast join**: `dim_patient` is tiny, so Spark ships a copy to every executor and joins locally
  instead of shuffling both tables by `patient_id`. Plan uses SortMergeJoin when broadcast is disabled:
  {smj_plan}; BroadcastHashJoin with `F.broadcast`: {bc_plan}.
""")
    print(OUT.read_text())


if __name__ == "__main__":
    main()
